import { build } from "../../apps/zoen/node_modules/esbuild/lib/main.js";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const result = await build({
  absWorkingDir: root,
  entryPoints: ["miniapps/deckcraft-ui/src/mcp-app.ts"],
  bundle: true,
  nodePaths: [resolve(root, "apps/zoen/node_modules")],
  preserveSymlinks: true,
  platform: "browser",
  format: "esm",
  target: ["safari17"],
  minify: true,
  legalComments: "inline",
  metafile: true,
  define: { "process.env.NODE_ENV": '"production"' },
  write: false,
});
if (Object.values(result.metafile.outputs).some((value) => value.imports.length))
  throw Error("The official App bootstrap must be self-contained");
const script = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><meta name="color-scheme" content="light dark"><title>Presentation</title><style>html,body{margin:0;width:100%;height:100%;overflow:hidden;background:transparent}#deckcraft_canvas{position:absolute;inset:0;width:100%;height:100%;display:block}#deckcraft_loading{position:absolute;inset:0;pointer-events:none}</style></head><body><canvas id="deckcraft_canvas"></canvas><div id="deckcraft_loading" aria-hidden="true"></div><script type="module">${script}</script></body></html>`;
if (Buffer.byteLength(html) > 8 * 1024 * 1024)
  throw Error("MCP resource exceeds existing HTML bound");
const sources = {};
for (const file of Object.keys(result.metafile.inputs).sort())
  sources[file] = createHash("sha256")
    .update(await readFile(resolve(root, file)))
    .digest("hex");
const manifest = {
  resourceUri: "ui://zoen/deckcraft/index.html",
  sha256: createHash("sha256").update(html).digest("hex"),
  bytes: Buffer.byteLength(html),
  sources,
};
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = input.match(/^apps\/zoen\/node_modules\/((?:@[^/]+\/)?[^/]+)(?:\/|$)/);
  if (!match || packages.has(match[1])) continue;
  const base = resolve(root, "apps/zoen/node_modules", match[1]);
  const pkg = JSON.parse(await readFile(resolve(base, "package.json"), "utf8"));
  let text;
  for (const name of ["LICENSE", "LICENSE.md", "LICENSE.txt", "license", "license.md"]) {
    try {
      text = await readFile(resolve(base, name), "utf8");
      break;
    } catch {}
  }
  if (!text) throw Error(`Missing bundled dependency license: ${pkg.name}`);
  packages.set(pkg.name, { name: pkg.name, version: pkg.version, license: pkg.license, text });
}
const bundled = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name));
const notices = bundled
  .map(
    (pkg) =>
      `===== ${pkg.name}@${pkg.version} (${pkg.license}) =====\n${pkg.text.replaceAll("\r\n", "\n").trim()}\n`,
  )
  .join("\n");
manifest.bundledDependencies = bundled.map(({ name, version, license }) => ({
  name,
  version,
  license,
}));
const outputs = {
  "miniapps/deckcraft-ui/BOOTSTRAP-LICENSES.txt": notices,
  "apps/zoen/src/miniapps/vendor/deckcraft-bootstrap.ts": `// Generated by miniapps/deckcraft-ui/build-bootstrap.mjs.\n// prettier-ignore\nexport const bootstrapManifest = ${JSON.stringify(manifest)} as const;\n// prettier-ignore\nexport default ${JSON.stringify(html)};\n`,
  "apps/zoen/src/miniapps/vendor/deckcraft-bootstrap.manifest.json": `${JSON.stringify(manifest, null, 2)}\n`,
  "crates/miniapps/resources/deckcraft.html": html,
};
for (const [name, content] of Object.entries(outputs)) {
  const path = resolve(root, name);
  if (process.argv.includes("--check")) {
    if ((await readFile(path, "utf8")) !== content)
      throw Error(`Stale DeckCraft bootstrap: ${name}`);
  } else await writeFile(path, content);
}
