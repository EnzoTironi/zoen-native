import { build } from "../../apps/zoen/node_modules/esbuild/lib/main.js";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const source = resolve(root, "apps/zoen/src/miniapps");
const result = await build({
  absWorkingDir: root,
  entryPoints: [resolve(source, "runtime-browser.ts")],
  bundle: true,
  preserveSymlinks: true,
  platform: "browser",
  format: "iife",
  globalName: "__zoenRuntimeSupport",
  target: ["safari17"],
  minify: true,
  legalComments: "inline",
  metafile: true,
  write: false,
});
if (Object.values(result.metafile.outputs).some((value) => value.imports.length))
  throw Error("The trusted runtime loader must be self-contained");
const script = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const sources = {};
for (const input of Object.keys(result.metafile.inputs).sort())
  sources[input] = createHash("sha256")
    .update(await readFile(resolve(root, input)))
    .digest("hex");
const output = {
  "runtime-support.ts": `// Generated by miniapps/deckcraft-ui/build-runtime.mjs.\n// prettier-ignore\nexport const runtimeSupportScript = ${JSON.stringify(script)};\n`,
  "runtime-support.manifest.json": `${JSON.stringify(
    {
      bytes: Buffer.byteLength(script),
      sha256: createHash("sha256").update(script).digest("hex"),
      sources,
      notice: "@noble/hashes 2.4.0: MIT; vendored license in miniapps/deckcraft-ui/licenses/",
    },
    null,
    2,
  )}\n`,
};
for (const [name, bytes] of Object.entries(output)) {
  const path = resolve(source, "vendor", name);
  if (process.argv.includes("--check")) {
    if ((await readFile(path, "utf8")) !== bytes) throw Error(`Stale runtime support: ${name}`);
  } else await writeFile(path, bytes);
}
