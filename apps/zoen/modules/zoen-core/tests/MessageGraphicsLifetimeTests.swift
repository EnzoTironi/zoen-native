import Foundation

@main struct MessageGraphicsLifetimeTests {
  static func main() {
    var model = ZoenMessageReceiptPresentation()
    let initial = model.accept(owner: "message_a", shape: .clock, propsDelivered: true)
    precondition(!initial.revealFull && !initial.revealPartial)
    model.windowChanged(visible: true)
    _ = model.accept(owner: "message_a", shape: .clock, propsDelivered: false)
    let sent = model.accept(owner: "message_a", shape: .single, propsDelivered: true)
    precondition(sent.revealFull && !sent.revealPartial)
    let delivered = model.accept(owner: "message_a", shape: .double, propsDelivered: true)
    precondition(!delivered.revealFull && delivered.revealPartial)
    let same = model.accept(owner: "message_a", shape: .double, propsDelivered: true)
    precondition(!same.revealFull && !same.revealPartial)
    model.windowChanged(visible: false)
    _ = model.accept(owner: "message_a", shape: .clock, propsDelivered: false)
    model.windowChanged(visible: true)
    let staleAttachLayout = model.accept(owner: "message_a", shape: .clock, propsDelivered: false)
    precondition(!staleAttachLayout.revealFull && !staleAttachLayout.revealPartial)
    let lateHistoricalProps = model.accept(owner: "message_a", shape: .double, propsDelivered: true)
    precondition(!lateHistoricalProps.revealFull && !lateHistoricalProps.revealPartial)
    _ = model.accept(owner: "message_b", shape: .single, propsDelivered: true)
    let currentAcknowledgement = model.accept(owner: "message_b", shape: .double, propsDelivered: true)
    precondition(currentAcknowledgement.revealPartial)
    let recycled = model.accept(owner: "message_c", shape: .double, propsDelivered: true)
    precondition(recycled.resetAnimations && !recycled.revealFull && !recycled.revealPartial)
    model.invalidate()
    let invalidRecovery = model.accept(owner: "message_c", shape: .clock, propsDelivered: true)
    precondition(!invalidRecovery.revealFull && !invalidRecovery.revealPartial)
    model.windowChanged(visible: false)
    let hidden = model.accept(owner: "message_c", shape: .single, propsDelivered: true)
    precondition(!hidden.revealFull && !hidden.revealPartial)
    model.windowChanged(visible: true)
    _ = model.accept(owner: "message_c", shape: .single, propsDelivered: false)
    let firstVisibleChange = model.accept(owner: "message_c", shape: .double, propsDelivered: true)
    precondition(!firstVisibleChange.revealPartial)
    print("Receipt presentation baseline/recycle/reattach assertions passed")
  }
}
