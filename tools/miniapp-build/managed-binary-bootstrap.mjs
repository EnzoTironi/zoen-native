import { build } from "../../apps/zoen/node_modules/esbuild/lib/main.js";
import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export async function buildManagedBinaryBootstrap(editor, outputDir, check = false) {
  if (!["deckcraft", "gridcraft", "wordcraft", "photocraft", "pdfcraft"].includes(editor))
    throw Error("Unsupported binary App");
  if (editor !== "deckcraft" && !outputDir)
    throw Error("This editor requires an explicit build directory");
  const title = {
    deckcraft: "Presentation",
    gridcraft: "Workbook",
    wordcraft: "Document",
    photocraft: "Image",
    pdfcraft: "PDF",
  }[editor];
  const result = await build({
    absWorkingDir: root,
    entryPoints: [`miniapps/${editor}-ui/src/mcp-app.ts`],
    bundle: true,
    nodePaths: [resolve(root, "apps/zoen/node_modules")],
    preserveSymlinks: true,
    platform: "browser",
    format: "esm",
    target: ["safari17"],
    minify: true,
    legalComments: "inline",
    metafile: true,
    define: { "process.env.NODE_ENV": '"production"' },
    write: false,
  });
  if (Object.values(result.metafile.outputs).some((value) => value.imports.length))
    throw Error("The official App bootstrap must be self-contained");
  const script = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
  const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><meta name="color-scheme" content="light dark"><title>${title}</title><style>html,body{margin:0;width:100%;height:100%;overflow:hidden;background:transparent}#${editor}_canvas{position:absolute;inset:0;width:100%;height:100%;display:block}#${editor}_loading{position:absolute;inset:0;pointer-events:none}</style></head><body><canvas id="${editor}_canvas"></canvas><div id="${editor}_loading" aria-hidden="true"></div><script type="module">${script}</script></body></html>`;
  if (Buffer.byteLength(html) > 8 * 1024 * 1024)
    throw Error("MCP resource exceeds existing HTML bound");
  const sources = {};
  for (const file of Object.keys(result.metafile.inputs).sort())
    sources[file] = createHash("sha256")
      .update(await readFile(resolve(root, file)))
      .digest("hex");
  const manifest = {
    resourceUri: `ui://zoen/${editor}/index.html`,
    sha256: createHash("sha256").update(html).digest("hex"),
    bytes: Buffer.byteLength(html),
    sources,
  };
  const packages = new Map();
  for (const input of Object.keys(result.metafile.inputs)) {
    const match = input.match(/^apps\/zoen\/node_modules\/((?:@[^/]+\/)?[^/]+)(?:\/|$)/);
    if (!match || packages.has(match[1])) continue;
    const base = resolve(root, "apps/zoen/node_modules", match[1]);
    const pkg = JSON.parse(await readFile(resolve(base, "package.json"), "utf8"));
    let text;
    for (const name of ["LICENSE", "LICENSE.md", "LICENSE.txt", "license", "license.md"]) {
      try {
        text = await readFile(resolve(base, name), "utf8");
        break;
      } catch {}
    }
    if (!text) throw Error(`Missing bundled dependency license: ${pkg.name}`);
    packages.set(pkg.name, { name: pkg.name, version: pkg.version, license: pkg.license, text });
  }
  const bundled = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name));
  const notices = bundled
    .map(
      (pkg) =>
        `===== ${pkg.name}@${pkg.version} (${pkg.license}) =====\n${pkg.text.replaceAll("\r\n", "\n").trim()}\n`,
    )
    .join("\n");
  manifest.bundledDependencies = bundled.map(({ name, version, license }) => ({
    name,
    version,
    license,
  }));
  const outputs =
    editor === "deckcraft"
      ? {
          "miniapps/deckcraft-ui/BOOTSTRAP-LICENSES.txt": notices,
          "apps/zoen/src/miniapps/vendor/deckcraft-bootstrap.ts": `// Generated by miniapps/deckcraft-ui/build-bootstrap.mjs.\n// prettier-ignore\nexport const bootstrapManifest = ${JSON.stringify(manifest)} as const;\n// prettier-ignore\nexport default ${JSON.stringify(html)};\n`,
          "apps/zoen/src/miniapps/vendor/deckcraft-bootstrap.manifest.json": `${JSON.stringify(manifest, null, 2)}\n`,
          "crates/miniapps/resources/deckcraft.html": html,
        }
      : {
          [`${editor}.html`]: html,
          [`${editor}-bootstrap.manifest.json`]: `${JSON.stringify(manifest, null, 2)}\n`,
          // Endpoint-neutral defaults stay unavailable until an operator binds
          // the actual sealed runtime with buildBinaryResourceManifest.
          [`${editor}.manifest.json`]: `${JSON.stringify({
            id: editor, name: {
              gridcraft: "GridCraft", wordcraft: "WordCraft", photocraft: "PhotoCraft", pdfcraft: "PdfCraft",
            }[editor], resourceUri: manifest.resourceUri,
            mimeType: "text/html;profile=mcp-app", capabilities: [], allowedDomains: [],
            linkDomains: [], networkPurpose: "", permissions: {},
            csp: { connectDomains: [], resourceDomains: [], frameDomains: [], baseUriDomains: [] },
            sha256: manifest.sha256, bytes: manifest.bytes,
          }, null, 2)}\n`,
          "BOOTSTRAP-LICENSES.txt": notices,
        };
  if (editor === "deckcraft") {
    const metadataPath = "crates/miniapps/resources/deckcraft.manifest.json";
    const previous = JSON.parse(await readFile(resolve(root, metadataPath), "utf8"));
    if (previous.id !== editor || previous.resourceUri !== manifest.resourceUri)
      throw Error("Existing Deck resource identity changed");
    outputs[metadataPath] =
      `${JSON.stringify({ ...previous, sha256: manifest.sha256, bytes: manifest.bytes }, null, 2)}\n`;
  }
  if (outputDir) await mkdir(outputDir, { recursive: true });
  for (const [name, content] of Object.entries(outputs)) {
    const path = resolve(outputDir ?? root, name);
    if (check) {
      if ((await readFile(path, "utf8")) !== content)
        throw Error(`Stale ${editor} bootstrap: ${name}`);
    } else await writeFile(path, content);
  }

  return manifest;
}
